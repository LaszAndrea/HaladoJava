package org.example.calculator;

public class Operations {

	double plus(double num, double num2) {
		return num + num2;
	}

	double minus(double num, double num2) {
		return num-num2;
	}

	double multiple(double num, double num2) {
		return num*num2;
	}

	double divide(double num, double num2) {
		return num/num2;
	}

}
